function eraCodeForWoAnalysis(id, fallbackName) {
  const n = Number(id);
  if (WO_ANALYSIS_TO_ERA[n]) return WO_ANALYSIS_TO_ERA[n];
  if (n === 57) return null;
  return `LAB-WO-${n}`;
}

function eraAnalyteCode(rawCode) {
  const key = String(rawCode || "").trim();
  if (!key) return "LINE";
  if (ANALYTE_ALIASES[key]) return ANALYTE_ALIASES[key];
  const upper = key.toUpperCase();
  if (ANALYTE_ALIASES[upper]) return ANALYTE_ALIASES[upper];
  return key.slice(0, 32);
}

function eraPanelCode(panel) {
  return PANEL_TO_ERA[panel] || PANEL_TO_ERA.OTHER;
}

