function addAliases(zone, extras) {
  const set = new Set(zone.woAliases || []);
  for (const a of extras) {
    const t = String(a || "").trim();
    if (t) set.add(t);
  }
  zone.woAliases = [...set];
}

function removeAliases(zone, drop) {
  const ban = new Set((drop || []).map((s) => String(s).trim()).filter(Boolean));
  zone.woAliases = (zone.woAliases || []).filter((a) => !ban.has(String(a).trim()));
}

