-- Cashier payment categories on revenue codes and folio payments.
ALTER TABLE "RevenueCode" ADD COLUMN IF NOT EXISTS "paymentCategory" TEXT;
ALTER TABLE "FolioPayment" ADD COLUMN IF NOT EXISTS "paymentCategory" TEXT;
CREATE INDEX IF NOT EXISTS "FolioPayment_paymentCategory_idx" ON "FolioPayment"("paymentCategory");

UPDATE "RevenueCode" SET "paymentCategory" = CASE "systemRole"
  WHEN 'ROOM' THEN 'LODGING'
  WHEN 'PKG' THEN 'LODGING'
  WHEN 'RATE_ADJ' THEN 'LODGING'
  WHEN 'BOARD' THEN 'LODGING'
  WHEN 'EARLY_CI' THEN 'LODGING'
  WHEN 'LATE_CO' THEN 'LODGING'
  WHEN 'CITY_TAX' THEN 'LODGING'
  WHEN 'CXL_NOSHOW' THEN 'LODGING'
  WHEN 'DISCOUNT' THEN 'LODGING'
  WHEN 'PROCEDURE' THEN 'CLINIC'
  WHEN 'DOCTOR' THEN 'CLINIC'
  WHEN 'DIAGNOSTIC' THEN 'CLINIC'
  WHEN 'LAB' THEN 'CLINIC'
  WHEN 'PHARMA' THEN 'CLINIC'
  WHEN 'TREATMENT' THEN 'CLINIC'
  WHEN 'SPA' THEN 'CLINIC'
  WHEN 'MEDICAL' THEN 'CLINIC'
  WHEN 'CLINIC_DISCOUNT' THEN 'CLINIC'
  WHEN 'FOOD' THEN 'FB'
  WHEN 'BEVERAGE' THEN 'FB'
  WHEN 'ALCOHOL' THEN 'FB'
  WHEN 'TOBACCO' THEN 'FB'
  WHEN 'MINIBAR' THEN 'FB'
  WHEN 'FB_DISCOUNT' THEN 'FB'
  WHEN 'LAUNDRY' THEN 'OTHER'
  WHEN 'TRANSFER' THEN 'OTHER'
  WHEN 'TAXI' THEN 'OTHER'
  WHEN 'TOUR' THEN 'OTHER'
  WHEN 'BANQUET' THEN 'OTHER'
  WHEN 'PARKING' THEN 'OTHER'
  WHEN 'HALL' THEN 'OTHER'
  WHEN 'ENTERTAINMENT' THEN 'OTHER'
  WHEN 'DAMAGE' THEN 'OTHER'
  WHEN 'OTHER' THEN 'OTHER'
  WHEN 'TELECOM' THEN 'OTHER'
  WHEN 'RESORT_FEE' THEN 'OTHER'
  ELSE "paymentCategory"
END
WHERE "paymentCategory" IS NULL AND "systemRole" IS NOT NULL;

UPDATE "FolioPayment" p
SET "paymentCategory" = rc."paymentCategory"
FROM "RevenueCode" rc
WHERE p."revenueCodeId" = rc.id
  AND p."paymentCategory" IS NULL
  AND rc."paymentCategory" IS NOT NULL;
