for (const loc of ['en', 'az', 'ru']) {
  const file = path.join(dir, `${loc}.json`);
  const data = JSON.parse(fs.readFileSync(file, 'utf8'));
  data.salesContracts = { ...data.salesContracts, ...extra[loc] };
  // Drop decorative restriction/deposit keys if a prior patch reintroduced them.
  for (const dead of [
    'minStay',
    'cta',
    'ctd',
    'depositRequired',
    'depositAmount',
    'conditions',
    'moreActions',
  ]) {
    delete data.salesContracts[dead];
  }
  fs.writeFileSync(file, `${JSON.stringify(data, null, 2)}\n`, 'utf8');
  console.log('patched', loc);
}
